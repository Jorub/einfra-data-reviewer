source('R/inventory.R')
library(ncdf4)
root <- tempfile('inventory-input-');out <- tempfile('inventory-reports-')
dir.create(root);dir.create(out)
make <- function(path) {
 dir.create(dirname(path),recursive=TRUE,showWarnings=FALSE)
 x <- ncdim_def('lon','degrees_east',c(-90,90));y<-ncdim_def('lat','degrees_north',c(-45,45))
 t <- ncdim_def('time','days since 2000-01-01',0:1)
 a<-ncvar_def('t2m','K',list(x,y,t),-9999)
 b<-ncvar_def('precipitation','mm/day',list(x,y,t),-9999)
 n<-nc_create(path,list(a,b));nc_close(n)
}
f<-file.path(root,'temperature','raw','synthetic_monthly.nc');make(f)
make(file.path(root,'temperature','raw','.ipynb_checkpoints','ignored.nc'))
make(file.path(root,'other','radiation','shortrad','synthetic_daily.nc4'))
writeLines('not netcdf',file.path(root,'broken.nc'))
file.symlink(file.path(root,'temperature'),file.path(root,'linked'))
before<-tools::md5sum(f)
x<-inventory_netcdf(root,out)
stopifnot(nrow(x)==5, sum(x$inspection_status=='ERROR')==1)
stopifnot(identical(before,tools::md5sum(f)))
stopifnot(!any(grepl('checkpoints|linked',x$path)))
stopifnot(all(x$family_hint[grepl('shortrad',x$path)]=='shortrad'))
stopifnot(all(x$stage_hint[x$family_hint=='temperature']=='raw'))
stopifnot(file.exists(file.path(out,'inventory-summary.csv')))
s <- read.csv(file.path(out,'inventory-summary.csv'))
stopifnot(sum(s$variable_records)==nrow(x),any(s$inspection_status=='ERROR'))
stopifnot(inherits(try(inventory_netcdf(root,file.path(root,'reports')),silent=TRUE),'try-error'))
unlink(c(root,out),recursive=TRUE)
cat('Inventory tests passed: multi-variable files, family hints, corrupt file isolation, hidden/symlink exclusion, output boundary and unchanged inputs.\n')
