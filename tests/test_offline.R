source("R/reviewer.R")
f <- tempfile(fileext = ".csv")
write.csv(data.frame(id=c(1,1,3), value=c(2,-4,NA)),f,row.names=FALSE)
x <- check_csv(f,c("id","value"),"value",list(value=c(0,10)),"id")
stopifnot(sum(x$status=="FAIL")==3)
write.csv(data.frame(id=1:3,value=c(0,2,10)),f,row.names=FALSE)
y <- check_csv(f,c("id","value"),"value",list(value=c(0,10)),"id")
stopifnot(all(y$status=="PASS"))
write.csv(data.frame(id=1:2),f,row.names=FALSE)
z <- check_csv(f,c("id","value"),"value",list(value=c(0,10)),"id")
stopifnot(sum(z$status=="FAIL")==3)
.einfra$key <- "SYNTHETIC_SENTINEL_NOT_A_REAL_KEY"
p <- as.character(prepare_review(x))
stopifnot(!grepl(.einfra$key,p,fixed=TRUE),!grepl(f,p,fixed=TRUE))
stopifnot(inherits(try(review_checks(x,"fake",p),silent=TRUE),"try-error"))
stopifnot(inherits(try(review_checks(x,"fake","stale",send=TRUE),silent=TRUE),"try-error"))
clear_api_key(); stopifnot(!exists("key",envir=.einfra,inherits=FALSE))
unlink(f)
cat("Offline validation, payload isolation, and approval tests passed. No network calls made.\n")
